'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const on = (ch) => (cb) => { const h = (_e, p) => cb(p); ipcRenderer.on(ch, h); return () => ipcRenderer.off(ch, h); };

contextBridge.exposeInMainWorld('talkme', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  updateSettings: (patch) => ipcRenderer.invoke('settings:update', patch),
  getStatus: () => ipcRenderer.invoke('status:get'),
  startServices: () => ipcRenderer.invoke('services:start'),
  stopServices: () => ipcRenderer.invoke('services:stop'),
  startCall: () => ipcRenderer.invoke('call:start'),
  stopCall: () => ipcRenderer.invoke('call:stop'),
  callSettings: (patch) => ipcRenderer.invoke('call:settings', patch),
  inject: (text) => ipcRenderer.invoke('call:inject', text),
  pickFile: (opts) => ipcRenderer.invoke('dialog:pickFile', opts),
  // the mic frame, and what the speaker played over the same stretch (the echo canceller's reference)
  sendAudio: (mic, ref) => ipcRenderer.send('audio:in', Buffer.from(mic.buffer, mic.byteOffset, mic.byteLength),
    ref ? Buffer.from(ref.buffer, ref.byteOffset, ref.byteLength) : null),
  aecDelay: (ms) => ipcRenderer.send('aec:delay', ms),
  echoTest: () => ipcRenderer.invoke('echo:test'),
  setPlaying: (p) => ipcRenderer.send('audio:playing', p),
  getAdapters: () => ipcRenderer.invoke('adapters:get'),
  getVoices: () => ipcRenderer.invoke('voices:get'),
  useVoice: (id) => ipcRenderer.invoke('voices:use', id),
  addVoiceFile: (name, file) => ipcRenderer.invoke('voices:add', name, { file }),
  addVoiceBytes: (name, bytes, ext) => ipcRenderer.invoke('voices:add', name, { bytes, ext }),
  removeVoice: (id) => ipcRenderer.invoke('voices:remove', id),
  useAdapter: (file) => ipcRenderer.invoke('adapters:use', file),
  useModel: (name) => ipcRenderer.invoke('model:use', name),
  adapterCatalog: () => ipcRenderer.invoke('adapters:catalog'),
  setAdapterNotes: (file, notes) => ipcRenderer.invoke('adapters:notes', file, notes),
  setAdapterLabel: (file, label) => ipcRenderer.invoke('adapters:label', file, label),
  renameAdapter: (file, name) => ipcRenderer.invoke('adapters:rename', file, name),
  removeAdapter: (file) => ipcRenderer.invoke('adapters:remove', file),
  onAdapters: on('adapters'),
  onThreshold: on('threshold'),
  rememberThreshold: (thr) => ipcRenderer.invoke('threshold:remember', thr),
  onCarryOn: on('carryOn'),
  setCarryOn: (p) => ipcRenderer.invoke('carryon:set', p),
  onSampling: on('sampling'),
  setSampling: (onOff) => ipcRenderer.invoke('sampling:set', onOff),
  tuneRun: (stage, recipe) => ipcRenderer.invoke('tune:run', stage, recipe),
  tuneStop: () => ipcRenderer.invoke('tune:stop'),
  tuneStatus: () => ipcRenderer.invoke('tune:status'),
  tuneRecipes: () => ipcRenderer.invoke('tune:recipes'),
  tuneRecipe: (file) => ipcRenderer.invoke('tune:recipe', file),
  tuneSaveRecipe: (file, text, saveAs) => ipcRenderer.invoke('tune:saveRecipe', file, text, saveAs),
  tuneResults: (file) => ipcRenderer.invoke('tune:results', file),
  tuneBases: () => ipcRenderer.invoke('tune:bases'),
  tuneWeights: () => ipcRenderer.invoke('tune:weights'),
  tuneProgress: (file) => ipcRenderer.invoke('tune:progress', file),
  baseGgufs: (repo) => ipcRenderer.invoke('bases:ggufs', repo),
  baseInspect: (spec) => ipcRenderer.invoke('bases:inspect', spec),
  baseAdd: (spec) => ipcRenderer.invoke('bases:add', spec),
  baseDownload: (name) => ipcRenderer.invoke('bases:download', name),
  onLog: on('log'),
  onStatus: on('status'),
  onTick: on('loop:tick'),
  onLoopError: on('loop:error'),
  onAudioStop: on('loop:audio-stop'),
  onPartial: on('stt:partial'),
  onTtsAudio: on('tts:audio'),
  onAecLevel: on('aec:level'),
  onTuneLog: on('tune:log'),
  onTuneDone: on('tune:done'),
});
